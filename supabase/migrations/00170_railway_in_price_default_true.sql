-- 00170_railway_in_price_default_true.sql
--
-- Клиент 2026-09-23: «по умолчанию ЖД тариф и грузоотправление должны
-- быть с галочкой, щас нету этого».
--
-- ЧТО БЫЛО. Две галочки решают, входит ли сумма в баланс поставщика:
--   • «ЖД в цене» — deals.railway_in_price, DEFAULT FALSE с 00018;
--   • «Грузоотправление в цене» — deals.additional_expenses_in_price,
--     DEFAULT TRUE с 00128 (та же просьба клиента от 2026-07-24).
-- То есть у грузоотправления умолчание уже было верным, а ЖД со дня
-- появления колонки приходилось поднимать руками на каждой сделке.
-- В форме создания сделки галочка ЖД стартовала снятой, а галочки
-- грузоотправления не было вовсе — значение проставлялось молча.
--
-- ЧТО МЕНЯЕТСЯ ЗДЕСЬ. Только умолчание колонки railway_in_price для
-- НОВЫХ строк. Форма создания правится отдельно (deals/new/page.tsx):
-- обе галочки подняты и обе видны, любую можно снять до создания.
--
-- СУЩЕСТВУЮЩИЕ СДЕЛКИ НЕ ТРОГАЕМ — как и 00128. В них стоит осознанный
-- выбор менеджера, а массовое поднятие галочки утянуло бы Сумму 1 в
-- баланс поставщика по всей базе: это движение денег, а клиент просил
-- «по умолчанию», то есть про новые сделки.
--
-- ROLLBACK: ALTER TABLE deals ALTER COLUMN railway_in_price SET DEFAULT FALSE;

ALTER TABLE deals ALTER COLUMN railway_in_price SET DEFAULT TRUE;

COMMENT ON COLUMN deals.railway_in_price IS
  'TRUE = Сумма 1 (ЖД, invoice_amount) входит в баланс поставщика. Умолчание TRUE с 00170 (клиент 2026-09-23); существующие сделки не менялись.';
