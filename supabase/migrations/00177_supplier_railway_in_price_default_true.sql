-- 00177_supplier_railway_in_price_default_true.sql
--
-- Клиент 2026-09-29: «по умолчанию галочки должны стоять, галочки влияющие
-- на баланс — сумма ЖД менеджер и грузоотправление». «Сумма ЖД менеджер» —
-- это Сумма 2, ЖД поставщика (00150), галочка «ЖД поставщика в цене»
-- (00176). У грузоотправления умолчание TRUE уже с 00128, у «ЖД в цене» —
-- с 00170. Здесь — третья галочка.
--
-- МЕНЯЕТСЯ ТОЛЬКО УМОЛЧАНИЕ для НОВЫХ сделок, как в 00128 и 00170.
-- Существующие сделки не трогаем: поднять галочку у них — это движение
-- денег в балансе (6 сделок KZ с Суммой 2, проверено 2026-09-29), его
-- решает владелец отдельно.
--
-- Форма создания сделки (deals/new) передаёт значение явно — галочка там
-- поднята и видна. Умолчание колонки нужно для остальных путей вставки
-- (копия сделки, импорт).
--
-- ROLLBACK: ALTER TABLE deals ALTER COLUMN supplier_railway_in_price SET DEFAULT FALSE;

ALTER TABLE deals ALTER COLUMN supplier_railway_in_price SET DEFAULT TRUE;

COMMENT ON COLUMN deals.supplier_railway_in_price IS
  'TRUE = Сумма 2 (ЖД поставщика, supplier_railway_amount) входит в баланс поставщика при равных валютах поставщика и логистики. Умолчание TRUE с 00177 (клиент 2026-09-29); существующие сделки не менялись.';
