/**
 * Сальдо ДТ-КТ Логистика — единственный источник правды по формуле.
 *
 * В БД сальдо не хранится: `compute_dt_kt_balance` (00011) не
 * используется, а единственная сохранённая величина — `opening_balance`
 * («Сальдо на 1 янв.»). Поэтому формула живёт здесь, а не в SQL, и
 * страница `dt-kt/page.tsx` (вместе с мобильными карточками) обязана
 * считать только через неё.
 *
 * ФОРМУЛА (клиент 2026-08-25):
 *
 *   Сальдо = Сальдо 1 янв + Возврат + Отгрузка
 *            + Штрафы + Сверхнорматив + ОГЭМ − Оплата
 *
 * ЗНАК РЕЗУЛЬТАТА: плюс = мы должны экспедитору, минус (красным) = нам
 * должны. Это не «прочтение» готового числа, а свойство самой формулы:
 * сальдо здесь — наш долг перед экспедитором.
 *
 *   отгрузка, штрафы, сверхнорматив, ОГЭМ  — экспедитор начисляет нам,
 *                                            долг РАСТЁТ  → со знаком «+»
 *   оплата                                 — мы платим ему,
 *                                            долг ПАДАЕТ  → со знаком «−»
 *   возврат                                — деньги вернулись нам,
 *                                            гасит нашу переплату → «+»
 *
 * ИСТОРИЯ ЗНАКА. 00133 (30.07) уже приводила формулу к этой конвенции и
 * разово перевернула знак сохранённых `opening_balance`. 12.08 формулу
 * вернули к прямой («знак не должен менять формулу»), но данные 00133
 * остались перевёрнутыми — и с тех пор минус на экране означал ровно
 * обратное подписи: PTC-Operator / Progressive oil trading показывал
 * −306 756 271,70 «нам должны» при отгрузке 430,7 млн против оплаты
 * 142,4 млн, то есть на деле это наш долг. Клиент 25.08: «+ это мы
 * должны, а − это нам должны, а сейчас кажется наоборот».
 *
 * ВОЗВРАТ оставлен КАК ЕСТЬ (клиент 25.08). Он, как и «Сальдо 1 янв.»,
 * входит со своим знаком и в этой правке не менялся — развернулись
 * только оплата, отгрузка, штрафы, сверхнорматив и ОГЭМ. Единственная
 * запись с возвратом — UE-LOGISTIC / АБ Линк — как давала 0,00, так и
 * даёт: −578 000,00 + 578 000,00 = 0,00.
 *
 * «Сальдо на 1 янв.» читается КАК ЕСТЬ, без разворотов на лету, и
 * хранится в той же конвенции, что и итог: минус — нам должны на 1
 * января. Записи, введённые руками в обратной конвенции после 00133,
 * выравнивает 00152 — иначе одна колонка живёт в двух конвенциях и ни
 * одна формула не может быть права для обеих.
 *
 * ОТГРУЗКА приходит не из этой таблицы, а суммой `shipped_tonnage_amount`
 * реестра по паре (экспедитор, группа компаний) за год — её считает
 * страница и передаёт сюда.
 *
 * ОПЛАТА — сумма строк `dt_kt_payments`, а не хранимая
 * `dt_kt_logistics.payment`: хранимая заполняется триггером 00126, но
 * отстаёт от правок до ответа сервера. Её тоже считает страница.
 *
 * ВАЛЮТА не конвертируется: слагаемые складываются как есть. Оплаты у
 * большинства экспедиторов в USD, а у сумм реестра валюта чаще всего не
 * проставлена — известное ограничение, вынесено в отдельную задачу.
 */

/** Слагаемые сальдо, хранящиеся в строке `dt_kt_logistics`. */
export type DtKtSaldoInput = {
  opening_balance: number | null;
  refund: number | null;
  fines: number | null;
  surcharge_preliminary: number | null;
  ogem: number | null;
};

/** Пустая ячейка — это ноль, а не «нет данных»: сальдо всегда считается. */
function n(v: number | null | undefined): number {
  return v ?? 0;
}

/**
 * @param row       строка ДТ-КТ (сальдо 1 янв, возврат, штрафы, сверхнорматив, ОГЭМ)
 * @param shipped   сумма отгрузки из реестра за год по паре «экспедитор + группа»
 * @param payment   сумма строк оплат
 * @returns         плюс = мы должны экспедитору, минус = нам должны
 */
export function computeDtKtSaldo(row: DtKtSaldoInput, shipped: number, payment: number): number {
  return n(row.opening_balance)
    + n(row.refund)
    + shipped
    + n(row.fines)
    + n(row.surcharge_preliminary)
    + n(row.ogem)
    - payment;
}
