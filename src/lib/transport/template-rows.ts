/**
 * Строка заголовка над таблицей. Генератор подменяет её целиком,
 * подставляя дату составления: «Заявка от 27.03.2026 г.».
 */
export const DATE_LINE_PLACEHOLDER = "Заявка от ____________ г.";

export function dateLine(ddmmyyyy: string): string {
  return `Заявка от ${ddmmyyyy} г.`;
}

/**
 * Сравнение названий строк при разборе загруженного бланка. Word рвёт
 * текст на куски произвольно, а люди ставят двойные пробелы и неразрывный
 * пробел, поэтому сверяем по нормализованному виду, а не буквально.
 */
export function normalizeRowLabel(raw: string): string {
  return raw.replace(/ /g, " ").replace(/\s+/g, " ").trim().toLowerCase();
}
