/**
 * Синонимы названий строк: одно и то же поле компании называют
 * по-разному. «Месяц отгрузки» в заявке на план ГУ — это «Период
 * перевозки» обычной заявки.
 */
export const ROW_ALIASES: Record<string, string[]> = {
  "Период перевозки": ["Месяц отгрузки", "Период отгрузки"],
  "Номера вагонов-цистерн": ["Номера вагонов", "Номера цистерн"],
  "Наименование железной дороги": ["Наименование ж/д", "Железная дорога"],
  "Принадлежность вагонов": ["Принадлежность вагонов-цистерн"],
};

/** Все написания строки, которые считаем этой строкой. */
export function rowVariants(label: string): string[] {
  return [label, ...(ROW_ALIASES[label] ?? [])];
}

/**
 * Строка заголовка над таблицей. В эталоне — «Заявка от … г.», но в
 * настоящих бланках встречается и «Дата 31.07.2026 г.» отдельной
 * строкой, а слово «Заявка» стоит ниже самостоятельным заголовком.
 * Поэтому подпись строки СОХРАНЯЕТСЯ, подставляется только дата.
 */
export const DATE_LINE_PLACEHOLDER = "Заявка от ____________ г.";

export const DATE_LINE_PREFIXES = ["Заявка от", "Дата"] as const;

/** Начало строки с датой, если абзац ею является. */
export function dateLinePrefix(text: string): string | null {
  const t = text.trim();
  for (const p of DATE_LINE_PREFIXES) {
    if (t.startsWith(p)) return p;
  }
  return null;
}

/** «Заявка от 27.03.2026 г.» или «Дата 27.03.2026 г.» — по образцу бланка. */
export function dateLine(ddmmyyyy: string, prefix: string = "Заявка от"): string {
  return `${prefix} ${ddmmyyyy} г.`;
}

/**
 * Сравнение названий строк при разборе загруженного бланка. Word рвёт
 * текст на куски произвольно, а люди ставят двойные пробелы и неразрывный
 * пробел, поэтому сверяем по нормализованному виду, а не буквально.
 */
export function normalizeRowLabel(raw: string): string {
  return raw.replace(/ /g, " ").replace(/\s+/g, " ").trim().toLowerCase();
}
