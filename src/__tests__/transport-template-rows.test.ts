import { describe, it, expect } from "vitest";
import {
  TEMPLATE_ROWS,
  DATE_LINE_PLACEHOLDER,
  dateLine,
  normalizeRowLabel,
} from "@/lib/transport/template-rows";

/**
 * Названия строк — контракт между эталонным бланком и генератором.
 *
 * Клиент 25.08.2026: «Поля будут в шаблоне как мы зададим и клиент будет
 * заполнять поля по тем названиям которые мы изначально зададим».
 * Компании уже получили бланк с этими названиями, поэтому переименование
 * строки — не косметика: у всех, кто не перезагрузит шаблон, эта строка
 * молча перестанет заполняться, и заявка уйдёт со старым значением.
 *
 * Список держится здесь явно, чтобы правка была осознанной, а не
 * побочным эффектом. Он сверен посимвольно с заявкой ОРТ от 27.03.2026.
 */

describe("строки шаблона заявки", () => {
  it("совпадают с бланком, разосланным компаниям", () => {
    expect([...TEMPLATE_ROWS]).toEqual([
      "Наименование нефтепродукта",
      "Кол-во в тоннах",
      "Назначение груза",
      "Станция назначения",
      "Код станции",
      "Тупик",
      "Наименование железной дороги",
      "Грузополучатель",
      "Код грузополучателя",
      "Адрес грузополучателя",
      "Код ОКПО получателя",
      "Код ЕТСНГ, ГНГ",
      "Особые отметки",
      "Грузоотправитель",
      "Принадлежность вагонов",
      "Экспедитор по ЖД",
      "Маршрут транспортировки",
      "Покупатель",
      "Период перевозки",
    ]);
  });

  it("названия не повторяются — иначе непонятно, какую строку заполнять", () => {
    expect(new Set(TEMPLATE_ROWS).size).toBe(TEMPLATE_ROWS.length);
  });
});

describe("сверка названий при разборе бланка", () => {
  // Word рвёт текст на куски, а люди ставят двойные и неразрывные
  // пробелы. Буквальное сравнение из-за этого не находит строку.
  it("не замечает лишних пробелов, регистра и неразрывного пробела", () => {
    const canon = normalizeRowLabel("Кол-во в тоннах");
    for (const variant of [
      "Кол-во  в тоннах",
      " Кол-во в тоннах ",
      "КОЛ-ВО В ТОННАХ",
      "Кол-во в тоннах",
      "Кол-во в тоннах\n",
    ]) {
      expect(normalizeRowLabel(variant)).toBe(canon);
    }
  });

  it("разные строки не схлопываются в одну", () => {
    const seen = new Set(TEMPLATE_ROWS.map(normalizeRowLabel));
    expect(seen.size).toBe(TEMPLATE_ROWS.length);
  });
});

describe("строка с датой", () => {
  it("подставляет дату составления в том же виде, что в образце", () => {
    expect(dateLine("27.03.2026")).toBe("Заявка от 27.03.2026 г.");
  });

  it("в пустом бланке стоит заглушка того же вида", () => {
    expect(DATE_LINE_PLACEHOLDER.startsWith("Заявка от ")).toBe(true);
    expect(DATE_LINE_PLACEHOLDER.endsWith(" г.")).toBe(true);
  });
});
