import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Порядок полей в форме заявки.
 *
 * Клиент 28.08.2026: «код не выбирается из справочника… если некоторые
 * поля подбираются в зависимости от других, мы эти зависимые поля
 * должны показывать ниже, чтобы пользователь сперва выбрал те поля, от
 * которых всё зависит».
 *
 * Так и было: коды ЕТСНГ и ГНГ стояли обычными полями ввода в карточке
 * «Груз», а грузоотправитель — который вместе с продуктом эти коды и
 * определяет — жил на сто с лишним строк ниже, в другой карточке.
 * Менеджер видел пустые коды раньше, чем выбирал завод.
 *
 * Тест читает саму форму: JSX не даёт связать порядок полей с их
 * зависимостями, поэтому проверяем взаимное расположение по исходнику.
 * Перестановка поля обязана быть осознанной правкой этого файла.
 */

const SRC = readFileSync(
  join(process.cwd(), "src/components/transport/request-form.tsx"),
  "utf8",
);

const at = (needle: string): number => {
  const i = SRC.indexOf(needle);
  expect(i, `в форме нет «${needle}»`).toBeGreaterThan(-1);
  return i;
};

describe("зависимые поля стоят ниже определяющих", () => {
  it("продукт и завод — выше кодов груза", () => {
    const fuel = at('label="Наименование нефтепродукта"');
    const factory = at('label="Грузоотправитель — завод"');
    const etsng = at('label="Код ЕТСНГ"');
    expect(fuel).toBeLessThan(etsng);
    expect(factory).toBeLessThan(etsng);
  });

  it("станция назначения — выше её кода", () => {
    expect(at('label="Станция назначения"')).toBeLessThan(at('label="Код станции"'));
  });

  it("грузополучатель — выше своих реквизитов", () => {
    const consignee = at('label="Грузополучатель"');
    for (const derived of ['label="ИНН / БИН"', 'label="Код грузополучателя"', 'label="Код ОКПО"']) {
      expect(consignee).toBeLessThan(at(derived));
    }
  });

  it("тоннаж — выше вагонов, которые из него считаются", () => {
    expect(at('label="Кол-во, тонн"')).toBeLessThan(at('label="Вагонов"'));
  });

  it("завод выбирается раньше маршрута: его станция — начало маршрута", () => {
    expect(at('label="Грузоотправитель — завод"')).toBeLessThan(
      at('label="Маршрут транспортировки"'),
    );
  });
});

describe("значения из справочника не набираются руками", () => {
  const derivedFields = ["Код ЕТСНГ", "Код ГНГ", "Код станции", "Код грузополучателя", "Код ОКПО"];

  it.each(derivedFields)("«%s» показывается как подставленное, а не как поле ввода", (label) => {
    // Derived рисует значение только для чтения; Input дал бы поле,
    // в которое можно вписать что угодно мимо справочника.
    expect(SRC).toContain(`<Derived label="${label}"`);
  });

  it("продукт, завод, станция, грузополучатель и маршрут — выбор из списка", () => {
    for (const label of [
      "Наименование нефтепродукта",
      "Грузоотправитель — завод",
      "Станция назначения",
      "Грузополучатель",
      "Маршрут транспортировки",
      "Наименование железной дороги",
      "Принадлежность вагонов",
    ]) {
      const start = at(`label="${label}"`);
      const chunk = SRC.slice(start, start + 400);
      expect(chunk, label).toContain("SearchableSelect");
    }
  });

  it("плательщика по ЖД можно подставить из справочника", () => {
    expect(SRC).toContain("Плательщик из справочника");
  });

  it("дороги предлагаются списком, но список открытый", () => {
    // Батумская заявка добавила АЗЖД и ГРЖД — закрывать список нельзя.
    expect(SRC).toContain('list="transport-railways"');
    expect(SRC).toContain('<datalist id="transport-railways">');
  });
});

describe("пустые коды не проходят молча", () => {
  it("про отсутствующую пару «завод + продукт» форма предупреждает", () => {
    expect(SRC).toContain("codesMissing");
    expect(SRC).toContain("/spravochnik/cargo-codes");
  });
});
